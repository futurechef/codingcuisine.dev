// Bakes a word in Hershey Script 1 (single-stroke) into src/lib/wordmark.ts.
//
//   npm pack hersheytext && tar xzf hersheytext-*.tgz
//   node scripts/bake-wordmark.mjs package/svg_fonts/HersheyScript1.svg codingcuisine
//
// Letters that touch are merged into one continuous stroke, so the cursive
// word mostly draws in a single line. Output is in font units, y pointing down.

import { readFileSync, writeFileSync } from 'node:fs'

const [fontPath, word = 'codingcuisine'] = process.argv.slice(2)
if (!fontPath) { console.error('usage: node scripts/bake-wordmark.mjs <HersheyScript1.svg> [word]'); process.exit(1) }

const svg = readFileSync(fontPath, 'utf8')
const glyphs = new Map()
for (const m of svg.matchAll(/<glyph unicode="(.)"[^>]*?horiz-adv-x="([\d.]+)"(?:[^>]*?d="([^"]*)")?/g)) {
  glyphs.set(m[1], { adv: +m[2], d: m[3] ?? '' })
}

const strokes = []
let x = 0
for (const ch of word) {
  const g = glyphs.get(ch)
  if (!g) throw new Error('No glyph for ' + JSON.stringify(ch))
  let cur = null
  for (const [, cmd, px, py] of g.d.matchAll(/([ML])\s*(-?[\d.]+)\s+(-?[\d.]+)/g)) {
    const p = [+(x + +px).toFixed(1), +(-py).toFixed(1)]
    if (cmd === 'M') { cur = [p]; strokes.push(cur) } else cur.push(p)
  }
  x += g.adv
}

// Merge strokes whose ends touch (cursive joins between letters).
const merged = []
for (const s of strokes) {
  const prev = merged[merged.length - 1]
  const end = prev?.[prev.length - 1]
  if (end && Math.hypot(end[0] - s[0][0], end[1] - s[0][1]) < 2) prev.push(...s.slice(1))
  else merged.push(s.slice())
}

const out = `// GENERATED by scripts/bake-wordmark.mjs — do not edit.
// "${word}" in Hershey Script 1 (single-stroke), font units, y down.
//
// The Hershey Fonts were originally created by Dr. A. V. Hershey while working
// at the U. S. National Bureau of Standards.
// The format of the Font data in this distribution was originally created by
// James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821
// (mit-eddie!ci-dandelion!hurt).
// SVG font conversion by Windell H. Oskay, www.evilmadscientist.com, via the
// hersheytext package (MIT).

export const WORDMARK: [number, number][][] = ${JSON.stringify(merged)}
`
writeFileSync(new URL('../src/lib/wordmark.ts', import.meta.url), out)
console.log(`${word}: ${strokes.length} strokes → ${merged.length} after joins, ${merged.flat().length} points, width ${x}`)
